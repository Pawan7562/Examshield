// controllers/aiQuestionController.js
// Thin HTTP controller — delegates all AI logic to aiQuestionService

const { generateQuestionBatch, isApiKeyConfigured } = require('../services/aiQuestionService');

/**
 * GET /api/admin/ai/status
 * Returns whether the Gemini API key is properly configured.
 * Frontend uses this to show a warning banner.
 */
exports.getStatus = (req, res) => {
  const configured = isApiKeyConfigured();
  return res.json({
    success: true,
    data: {
      configured,
      model: 'gemini-1.5-flash',
      message: configured
        ? 'AI question generation is active. Questions will be fully generated by Google Gemini.'
        : 'GEMINI_API_KEY is not set. Questions will use high-quality built-in templates. Add a real key to backend/.env to enable full AI generation.',
      setupUrl: 'https://aistudio.google.com/app/apikey',
    },
  });
};

/**
 * POST /api/admin/ai/generate-questions
 * Body: {
 *   topic:      string   (required)
 *   difficulty: 'easy'|'medium'|'hard'   (default: 'medium')
 *   sources:    string[]  (default: ['leetcode'])
 *   count:      number    (default: 5, max 20)
 *   mode:       'partial'|'full'  (default: 'partial')
 * }
 */
exports.generateQuestions = async (req, res) => {
  try {
    const {
      topic,
      difficulty = 'medium',
      sources = ['leetcode'],
      count = 5,
      mode = 'partial',
    } = req.body;

    // ── Validation ────────────────────────────────────────────────────────────
    if (!topic || !topic.trim()) {
      return res.status(400).json({ success: false, message: 'Topic is required' });
    }

    if (!['easy', 'medium', 'hard'].includes(difficulty)) {
      return res.status(400).json({
        success: false,
        message: 'Invalid difficulty. Use: easy, medium, or hard',
      });
    }

    if (!Array.isArray(sources) || sources.length === 0) {
      return res.status(400).json({
        success: false,
        message: 'At least one source is required',
      });
    }

    const validSources = ['leetcode', 'codeforces', 'geeksforgeeks', 'hackerrank'];
    const invalidSources = sources.filter(s => !validSources.includes(s));
    if (invalidSources.length > 0) {
      return res.status(400).json({
        success: false,
        message: `Invalid sources: ${invalidSources.join(', ')}. Valid options: ${validSources.join(', ')}`,
      });
    }

    if (!['partial', 'full'].includes(mode)) {
      return res.status(400).json({
        success: false,
        message: 'Invalid mode. Use: partial or full',
      });
    }

    const requestedCount = Math.min(Math.max(parseInt(count) || 5, 1), 20);

    // ── Logging ───────────────────────────────────────────────────────────────
    console.log(`\n🤖 AI Question Generation Request`);
    console.log(`   Topic:      ${topic}`);
    console.log(`   Difficulty: ${difficulty}`);
    console.log(`   Sources:    ${sources.join(', ')}`);
    console.log(`   Count:      ${requestedCount}`);
    console.log(`   Mode:       ${mode}`);
    console.log(`   AI Active:  ${isApiKeyConfigured()}`);

    // ── Generation ────────────────────────────────────────────────────────────
    const startTime = Date.now();

    const result = await generateQuestionBatch({
      topic: topic.trim(),
      difficulty,
      sources,
      count: requestedCount,
      mode,
    });

    const elapsed = ((Date.now() - startTime) / 1000).toFixed(1);
    console.log(`\n✅ Generation complete: ${result.questions.length} questions in ${elapsed}s`);
    console.log(`   AI-generated: ${result.meta.aiGenerated}, Fallbacks: ${result.meta.fallbacks}`);

    // ── Response ──────────────────────────────────────────────────────────────
    return res.json({
      success: true,
      data: {
        questions: result.questions,
        meta: {
          ...result.meta,
          elapsedSeconds: parseFloat(elapsed),
          apiConfigured: result.apiConfigured,
        },
        errors: result.errors.length > 0 ? result.errors : undefined,
        apiStatus: {
          configured: result.apiConfigured,
          message: result.apiConfigured
            ? `${result.meta.aiGenerated} questions generated by Google Gemini AI`
            : `API key not configured — ${result.meta.fallbacks} high-quality template questions returned`,
        },
      },
    });

  } catch (error) {
    console.error('❌ AI Question Generation Error:', error);
    return res.status(500).json({
      success: false,
      message: 'Failed to generate questions. Please try again.',
      error: process.env.NODE_ENV === 'development' ? error.message : undefined,
    });
  }
};
